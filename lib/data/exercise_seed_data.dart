import 'package:uuid/uuid.dart';
import '../models/exercise.dart';

/// Deterministic IDs (not random UUIDs) so re-seeding is idempotent —
/// inserting with the same id + ConflictAlgorithm.replace just updates
/// the row rather than creating duplicates if we ever tweak this list.
const _uuidNamespace = 'gym-tracker-builtin-exercise';

String _id(String key) => Uuid().v5(Uuid.NAMESPACE_URL, '$_uuidNamespace:$key');

Exercise _e(
  String key,
  String name,
  MuscleGroup primary,
  Equipment equipment,
  ExerciseType type, {
  List<MuscleGroup> secondary = const [],
  String? instructions,
}) {
  return Exercise(
    id: _id(key),
    name: name,
    primaryMuscle: primary,
    secondaryMuscles: secondary,
    equipment: equipment,
    type: type,
    instructions: instructions,
    isCustom: false,
  );
}

